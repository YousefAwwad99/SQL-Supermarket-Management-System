
-- Calculate the total revenue from all completed orders.

SELECT 
SUM(total_sales) AS total_sales
FROM orders
WHERE order_status = 'Completed'


/*
Display each customer and the number of completed
orders they have placed.

Requirements:
- Include customers who have never placed an order.
- Display customer ID and customer name.
- Sort by total orders descending.

Expected Columns:
- c_id
- c_name
- total_orders
*/

SELECT 
c.c_id,
c.c_name,
COUNT(O.order_id) AS [number of completed orders]
FROM customers AS c
LEFT JOIN orders AS o
ON c.c_id = o.c_id
AND o.order_status = 'Completed'
GROUP BY c.c_id,
c.c_name
ORDER BY COUNT(O.order_id) DESC




/*
Find the top 5 products by total quantity sold.

Requirements:
- Include only completed orders.
- Calculate total units sold for each product.
- Sort by total units sold descending.

Expected Columns:
- p_id
- p_name
- total_units_sold
*/

SELECT TOP 5
p.p_id,
p.p_name,
SUM(o.quantity) AS total_units_sold
FROM products AS p
INNER JOIN order_details AS o
ON o.p_id = p.p_id
INNER JOIN orders AS od
ON od.order_id = o.order_id AND od.order_status = 'Completed'
GROUP BY p.p_id,
p.p_name
ORDER BY SUM(o.quantity) DESC


/*
Display products with fewer than 10 units in stock.

Requirements:
- Include products with no inventory record.
- Treat missing inventory as zero stock.
- Sort by quantity ascending.

Expected Columns:
- p_id
- p_name
- available_quantity

*/

SELECT 
p.p_id,
p.p_name,
CASE WHEN i.quantity IS NULL THEN 0 ELSE i.quantity END  quantity
FROM products AS p
LEFT JOIN inventory AS i
ON p.p_id = i.p_id
WHERE i.quantity < 10 OR i.quantity IS NULL
ORDER BY quantity ASC


/*

Calculate total revenue generated by each category.

Requirements:
- Include only completed orders.
- Use sold quantity multiplied by unit_price.
- Sort by category revenue descending.

Expected Columns:
- p_category
- category_revenue
*/



SELECT 
p_category,
SUM(od.quantity * od.unit_price) AS [total revenue generated by each category]
FROM products AS p
LEFT JOIN order_details AS od
ON od.p_id = p.p_id
LEFT JOIN orders AS o
ON o.order_id = od.order_id
WHERE o.order_status = 'Completed'
GROUP BY p_category
ORDER BY SUM(od.quantity * od.unit_price) DESC

/*
Calculate revenue and completed order count
for each month.

Requirements:
- Group sales by year and month.
- Include only completed orders.
- Sort chronologically.

Expected Columns:
- sales_year
- sales_month
- total_orders
- monthly_revenue
*/


SELECT 
YEAR(o.order_date) AS [year],
MONTH(o.order_date) AS [month],
COUNT(DISTINCT o.order_id) AS [total number of completed orders],
SUM(od.quantity * od.unit_price) AS [monthly_revenue]
FROM orders AS o
LEFT JOIN order_details AS od
ON od.order_id = o.order_id
WHERE o.order_status = 'Completed'
GROUP BY YEAR(o.order_date),
MONTH(o.order_date)
ORDER BY YEAR(o.order_date) , MONTH(o.order_date)


/*
Find customers who have never completed a purchase.

Requirements:
- Customers with only cancelled orders must appear.
- Customers with no orders must appear.

Expected Columns:
- c_id
- c_name
*/

SELECT 
c.c_id,
c.c_name
FROM customers AS c
WHERE NOT EXISTS 
(SELECT 1 FROM orders AS o WHERE o.c_id = c.c_id AND o.order_status = 'Completed')


/*
Calculate the average value of completed orders.

Expected Columns:
- average_order_value
*/


SELECT 
AVG(total_sales) AS [avg]
FROM orders
WHERE order_status = 'Completed'
